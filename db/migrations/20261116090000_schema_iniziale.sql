-- Schema iniziale: le 14 tabelle di docs/architettura.md, allineate al
-- data dictionary v1 del team dati (data/data-dictionary.md).
-- Congelato al SAL 1: da qui ogni cambiamento è una migrazione nuova.
--
-- ID: interi che arrivano dai CSV. Solo dove scrive anche l'applicazione
-- (utente, anomalia, segnalazione) la colonna genera da sola i nuovi ID.
-- Ore sempre in UTC (timestamptz).

-- migrate:up

-- Anagrafiche

CREATE TABLE socio (
  id            integer PRIMARY KEY,
  nome          text NOT NULL,
  tipo          text NOT NULL CHECK (tipo IN ('famiglia', 'impresa', 'ente')),
  comune        text NOT NULL,
  data_adesione date NOT NULL
);

CREATE TABLE utente (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  ruolo         text NOT NULL CHECK (ruolo IN ('socio', 'operatore', 'admin')),
  socio_id      integer UNIQUE REFERENCES socio (id),
  -- un socio ha sempre il suo socio_id, un dipendente mai
  CHECK ((ruolo = 'socio') = (socio_id IS NOT NULL))
);

CREATE TABLE impianto (
  id                 integer PRIMARY KEY,
  nome               text NOT NULL,
  comune             text NOT NULL,
  lat                double precision NOT NULL,
  lon                double precision NOT NULL,
  kwp                double precision NOT NULL CHECK (kwp > 0),
  inclinazione_gradi double precision NOT NULL CHECK (inclinazione_gradi BETWEEN 0 AND 90),
  azimut_gradi       double precision NOT NULL CHECK (azimut_gradi BETWEEN -180 AND 180),  -- 0 = sud, -90 = est
  data_attivazione   date NOT NULL
);

CREATE TABLE parametro (
  chiave text PRIMARY KEY,
  valore double precision NOT NULL,
  fonte  text NOT NULL
);

CREATE TABLE verbale (
  id             integer PRIMARY KEY,
  data_assemblea date NOT NULL,
  testo          text NOT NULL,
  sintesi        text            -- da LLM
);

-- Serie orarie: chiave (id, ts)

CREATE TABLE produzione_oraria (
  impianto_id integer NOT NULL REFERENCES impianto (id),
  ts          timestamptz NOT NULL,
  kwh         double precision NOT NULL CHECK (kwh >= 0),
  PRIMARY KEY (impianto_id, ts)
);

CREATE TABLE meteo_orario (
  impianto_id                integer NOT NULL REFERENCES impianto (id),
  ts                         timestamptz NOT NULL,
  irraggiamento_wm2          double precision NOT NULL CHECK (irraggiamento_wm2 >= 0),           -- piano orizzontale
  irraggiamento_pannelli_wm2 double precision NOT NULL CHECK (irraggiamento_pannelli_wm2 >= 0),  -- piano dei moduli
  temperatura_c              double precision NOT NULL,
  nuvolosita_pct             double precision NOT NULL CHECK (nuvolosita_pct BETWEEN 0 AND 100),
  neve_cm                    double precision NOT NULL CHECK (neve_cm >= 0),
  PRIMARY KEY (impianto_id, ts)
);

CREATE TABLE consumo_orario (
  socio_id integer NOT NULL REFERENCES socio (id),
  ts       timestamptz NOT NULL,
  kwh      double precision NOT NULL CHECK (kwh >= 0),
  PRIMARY KEY (socio_id, ts)
);

-- Mensili: `mese` è sempre il primo giorno del mese

CREATE TABLE bolletta (
  id          integer PRIMARY KEY,
  socio_id    integer NOT NULL REFERENCES socio (id),
  mese        date NOT NULL CHECK (extract(day FROM mese) = 1),
  kwh         double precision NOT NULL CHECK (kwh >= 0),
  importo_eur numeric(10, 2) NOT NULL,
  UNIQUE (socio_id, mese)
);

-- Derivate: le riempie il batch Python

CREATE TABLE previsione_produzione (
  impianto_id integer NOT NULL REFERENCES impianto (id),
  ts          timestamptz NOT NULL,
  kwh_previsti double precision NOT NULL CHECK (kwh_previsti >= 0),
  PRIMARY KEY (impianto_id, ts)
);

CREATE TABLE previsione_consumo (
  socio_id     integer NOT NULL REFERENCES socio (id),
  ts           timestamptz NOT NULL,
  kwh_previsti double precision NOT NULL CHECK (kwh_previsti >= 0),
  PRIMARY KEY (socio_id, ts)
);

CREATE TABLE ripartizione_mensile (
  socio_id       integer NOT NULL REFERENCES socio (id),
  mese           date NOT NULL CHECK (extract(day FROM mese) = 1),
  kwh_condivisi  double precision NOT NULL CHECK (kwh_condivisi >= 0),
  incentivo_eur  numeric(10, 2) NOT NULL CHECK (incentivo_eur >= 0),
  co2_evitata_kg double precision NOT NULL CHECK (co2_evitata_kg >= 0),
  PRIMARY KEY (socio_id, mese)
);

-- Ci scrivono il batch (aggiunge solo le nuove) e l'operatore (le chiude)
CREATE TABLE anomalia (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  impianto_id integer NOT NULL REFERENCES impianto (id),
  inizio      timestamptz NOT NULL,
  fine        timestamptz CHECK (fine >= inizio),   -- null se ancora in corso
  tipo        text CHECK (tipo IN ('guasto', 'sporcizia', 'stringa', 'neve')),  -- null se il modello non lo sa
  score       double precision CHECK (score BETWEEN 0 AND 1),
  stato       text NOT NULL DEFAULT 'aperta' CHECK (stato IN ('aperta', 'chiusa'))
);

-- Le prime arrivano dai CSV, le nuove dal backend.
-- Categorie e urgenze: quelle del data dictionary v1. null = LLM non disponibile.
CREATE TABLE segnalazione (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  socio_id        integer REFERENCES socio (id),      -- null per le comunicazioni interne
  impianto_id     integer REFERENCES impianto (id),   -- valore in uso, l'operatore può correggerlo
  impianto_id_llm integer REFERENCES impianto (id),   -- dall'LLM, mai modificato
  ts              timestamptz NOT NULL DEFAULT now(),
  canale          text NOT NULL CHECK (canale IN ('email', 'portale', 'interno')),
  testo           text NOT NULL,
  categoria_llm   text,   -- dall'LLM, mai modificata
  urgenza_llm     text,   -- dall'LLM, mai modificata
  categoria       text,   -- valore in uso, l'operatore può correggerlo
  urgenza         text,   -- valore in uso, l'operatore può correggerlo
  stato           text NOT NULL DEFAULT 'aperta' CHECK (stato IN ('aperta', 'in_corso', 'chiusa')),
  CHECK (categoria_llm IN ('guasto_impianto', 'bolletta_pagamenti', 'incentivi_ripartizione',
                           'adesione_recesso', 'informazioni', 'reclamo')),
  CHECK (categoria     IN ('guasto_impianto', 'bolletta_pagamenti', 'incentivi_ripartizione',
                           'adesione_recesso', 'informazioni', 'reclamo')),
  CHECK (urgenza_llm IN ('alta', 'media', 'bassa')),
  CHECK (urgenza     IN ('alta', 'media', 'bassa'))
);

-- migrate:down

DROP TABLE segnalazione, anomalia, ripartizione_mensile, previsione_consumo,
  previsione_produzione, bolletta, consumo_orario, meteo_orario,
  produzione_oraria, verbale, parametro, impianto, utente, socio;
